"""Tests for the report analysis attribution (_build_analysis_subtitle).

The "Generated by …" line credits the analysis AUTHOR from the analysis.md
frontmatter, rendered as-is and provider-neutral. The author records their own
model (see analyze-results.md) — which is distinct from the eval SUBJECT model
that the report shows separately in its Model row. These tests pin the render
contract, including that the subject model (run_result.model) never leaks into
the author line.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
sys.path.insert(0, str(Path(__file__).parent.parent / "skills" / "eval-run" / "scripts"))

from report import _build_analysis_subtitle  # noqa: E402


def _subtitle(meta, run_result=None):
    return _build_analysis_subtitle(
        meta, {"judges": {}, "per_case": {}}, run_result or {}, None)


def test_author_agent_and_model_rendered_verbatim():
    out = _subtitle({"agent": "Claude Code", "model": "claude-opus-4-8"})
    assert ("Generated by <strong>Claude Code</strong> "
            "(<code>claude-opus-4-8</code>)") in out


def test_subject_model_does_not_leak_into_author_line():
    # The eval subject model (run_result.model) must not affect the author line.
    out = _subtitle(
        {"agent": "Claude Code", "model": "claude-opus-4-8"},
        {"agent": "claude-code", "model": "z-ai/glm-5.3-flash"})
    assert "(<code>claude-opus-4-8</code>)" in out
    assert "glm-5.3-flash" not in out


def test_non_anthropic_author_model_renders():
    # Provider-neutral: any author model id renders as-is.
    out = _subtitle({"agent": "Codex", "model": "gpt-5-codex"})
    assert "<strong>Codex</strong>" in out
    assert "<code>gpt-5-codex</code>" in out


def test_agent_only_when_no_model():
    out = _subtitle({"agent": "Claude Code"})
    assert "Generated by <strong>Claude Code</strong> from" in out


def test_defaults_to_claude_code_when_nothing_available():
    out = _subtitle({})
    assert "Generated by <strong>Claude Code</strong>" in out
